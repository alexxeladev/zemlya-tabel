/**
 * Какие строки табеля вахты показывать в режиме расчётной половины
 * (task_vahta_columns_order, решение заказчика 25.09.2026).
 *
 * **Нет смен в выбранной половине — строки нет.** Режим половины отвечает на
 * вопрос «кто выходил в эти полмесяца», и человек с пустой сеткой в нём только
 * мешает: на деве в сентябре таких строк 21 из 71. В режиме месяца показываются
 * все, как раньше.
 *
 * Правило распространяется и на строки, у которых за половину ЕСТЬ деньги без
 * единой смены: официальная выплата считается по календарным дням на посту, а
 * не по сменам, поэтому у отработавшего только первую половину во второй
 * остаётся банковская выплата и отрицательная «к выплате» (сентябрь: 6 строк,
 * 81 997,50 ₽ через банк и 35 258,92 ₽ налога). Заказчику это показано, решение
 * — прятать всё равно. Следствие, которое надо помнить: **в режиме половины
 * сумма видимых строк меньше итогов подвала** — они считаются на сервере по
 * всем строкам, и разнесение по юрлицам тоже. Поэтому счётчик над таблицей
 * называет число скрытых строк: пропажа людей не должна выглядеть поломкой.
 *
 * Считаются смены ПОКАЗАННОГО отрезка: в режиме половины сервер кладёт в
 * `shifts` смены только этой половины (`GuardRowResult.only_half`), а `days`
 * остаются на весь месяц — они отметки, а не итог.
 */

/** Минимум полей строки, от которых зависит показ. */
export interface VahtaRowLike {
  shifts: number
}

/** Есть ли у строки смены в показанном отрезке. */
export function hasShiftsInPeriod(row: VahtaRowLike): boolean {
  return row.shifts > 0
}

/**
 * Показывать ли строку.
 *
 * `viewHalf === null` — режим месяца, показываются все строки.
 * `edited` — строку правили в этом сеансе: она остаётся видимой, даже когда
 * смен в ней больше нет. Иначе снятая по ошибке последняя смена прятала бы
 * строку прямо под курсором, и вернуть её было бы нечем.
 */
export function showsInPeriod(
  row: VahtaRowLike,
  viewHalf: number | null,
  edited = false,
): boolean {
  if (viewHalf === null || edited) return true
  return hasShiftsInPeriod(row)
}

/**
 * Сколько РАЗНЫХ людей в наборе строк. Пустые слоты (человека нет) не считаются.
 *
 * Счётчик карточки места («4 чел. · 5 строк») строится по ПОКАЗАННЫМ строкам:
 * в режиме половины часть их скрыта, и счёт по всем строкам карточки давал
 * «4 чел.» над двумя строками — пропажа людей выглядела поломкой.
 */
export function countPeople(rows: { employee_id: number | null }[]): number {
  return new Set(rows.filter((r) => r.employee_id).map((r) => r.employee_id)).size
}

/** Сколько строк скрыто фильтром половины — для подписи над таблицей. */
export function hiddenInPeriodCount(
  rows: VahtaRowLike[],
  viewHalf: number | null,
  edited: ReadonlySet<number> = new Set(),
  idOf: (row: VahtaRowLike) => number = () => -1,
): number {
  if (viewHalf === null) return 0
  return rows.filter((r) => !showsInPeriod(r, viewHalf, edited.has(idOf(r)))).length
}
