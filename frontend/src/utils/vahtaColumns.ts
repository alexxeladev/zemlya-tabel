/**
 * Порядок колонок табеля вахты ПОСЛЕ сетки дней (task_vahta_columns_order).
 *
 * Порядок повторяет исходную таблицу бухгалтерии: строка читается слева направо
 * как сборка суммы — смен, зарплата, трудоустройство, премия, штраф, начислено,
 * оф. выплата, налог, к выплате. Раньше первым шло «Начислено», а следом то, из
 * чего оно сложилось: строка читалась справа налево, и бухгалтер не мог свериться
 * с привычным порядком.
 *
 * Здесь — ЕДИНСТВЕННОЕ описание порядка и подписей: по нему рисуется шапка
 * таблицы, от него считается ширина колонок и число колонок строки-спины зоны.
 * Ячейки строки помечены `data-col` тем же ключом, и порядок ключей в разметке
 * сторожит тест (`vahtaColumns.test.ts`) — иначе шапка и ячейки разъехались бы.
 *
 * «Начислено» в исходном файле бухгалтерии НЕТ, у нас есть: от него считается
 * разнесение по юрлицам. Стоит после штрафа, перед вычетами — там, где сумма
 * уже собрана, но ещё ничего не вычтено.
 */

export interface VahtaTailColumn {
  /** Ключ колонки. Он же `data-col` ячейки в разметке — по нему сверяют порядок. */
  key: string
  /** Подпись в шапке — как в исходной таблице бухгалтерии. */
  label: string
  /** Деньги: табельщику такая колонка не показывается вовсе. */
  money: boolean
  /** Ширина колонки, px. */
  width: number
}

/**
 * Колонки после сетки дней, в порядке исходной таблицы.
 *
 * «Трудоустройство» — не деньги: это кадровый признак «официально устроен»,
 * он приходит табельщику наравне со сменами (официальная ЗАРПЛАТА — деньги, и
 * её маскирует `finance_masking`, но самого признака это не касается).
 */
export const VAHTA_TAIL_COLUMNS: VahtaTailColumn[] = [
  { key: 'shifts', label: 'Смен', money: false, width: 48 },
  { key: 'salary', label: 'Зарплата', money: true, width: 96 },
  { key: 'employment', label: 'Трудоустройство', money: false, width: 116 },
  { key: 'premium', label: 'Премия', money: true, width: 92 },
  { key: 'penalty', label: 'Штраф', money: true, width: 92 },
  { key: 'accrued', label: 'Начислено', money: true, width: 104 },
  { key: 'official', label: 'Оф. выплата', money: true, width: 104 },
  { key: 'tax', label: 'Налог', money: true, width: 92 },
  // Шире прочих: под суммой может стоять подпись «долг 12 615 ₽».
  { key: 'payout', label: 'К выплате', money: true, width: 124 },
]

/**
 * Колонки, показанные актору. Набор зависит ТОЛЬКО от того, видит ли он деньги,
 * и не зависит от режима отображения: в режиме половины месяца колонки те же,
 * меняются лишь суммы в них.
 */
export function vahtaTailColumns(showMoney: boolean): VahtaTailColumn[] {
  return VAHTA_TAIL_COLUMNS.filter((c) => showMoney || !c.money)
}

/** Ширина колонки по ключу — шапка и ячейка строки берут её из одного места. */
export function vahtaColWidth(key: string): number {
  return VAHTA_TAIL_COLUMNS.find((c) => c.key === key)?.width ?? 96
}

/** Подпись колонки налога со ставкой: «Налог 40 %». Ставки нет — просто «Налог». */
export function vahtaTaxLabel(percent: string | number | null | undefined): string {
  const value = percent === null || percent === undefined ? NaN : Number(percent)
  return Number.isFinite(value) && value !== 0 ? `Налог ${value} %` : 'Налог'
}

/**
 * Трудоустройство словом, как в исходной таблице.
 *
 * Пустой слот (места есть, человека нет) — прочерк: это «данных нет». У
 * человека признак известен всегда, поэтому «Официальный» / «Неофициальный» —
 * пустая ячейка здесь читалась бы как «не заполнено».
 */
export function employmentLabel(
  isOfficial: boolean,
  hasEmployee: boolean,
): string {
  if (!hasEmployee) return '—'
  return isOfficial ? 'Официальный' : 'Неофициальный'
}
