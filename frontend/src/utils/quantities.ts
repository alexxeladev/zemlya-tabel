/**
 * Какие блоки количественного показателя показывать над табелем.
 *
 * Бэкенд отдаёт показатель по ВСЕМ отделам с флагом, попавшим в область
 * видимости запроса («все отделы» у admin/accountant — значит все). Фильтры же
 * табеля (юрлицо над таблицей и фильтры в заголовках колонок) — клиентские,
 * бэк о них не знает. Поэтому без этого отбора блок ввода АРМ/Заявок висел над
 * табелем даже тогда, когда ни одного такого отдела в выборке не осталось:
 * выбрана компания «К-Сервис» и отдел «Сервис Доп.Услуги Собственникам», а
 * сверху таблицы ввода показателя ИТ и HR.
 *
 * Правило: показываем ровно те отделы, чьи СТРОКИ есть в текущем отфильтрованном
 * представлении. Ни одного — блока нет вовсе (компонент отдаёт `null` на пустом
 * списке). Виден только ИТ — блока HR нет, и наоборот.
 *
 * Отбор строится ОТ УЖЕ ОТФИЛЬТРОВАННЫХ СТРОК, а не от разбора самих фильтров:
 * фильтров пять и они сужают выдачу вместе, повторять их логику здесь значило бы
 * завести вторую копию правила, которая разойдётся с таблицей.
 */
export function quantitiesForVisibleDepartments<T extends { department_id: number }>(
  quantities: T[],
  /** отделы видимых строк; null/undefined — «Без отдела», показателя у него нет */
  visibleDepartmentIds: Iterable<number | null | undefined>,
): T[] {
  const ids = new Set<number>()
  for (const id of visibleDepartmentIds) {
    if (id != null) ids.add(id)
  }
  return quantities.filter((q) => ids.has(q.department_id))
}
